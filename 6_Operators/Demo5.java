// Divide 9 by 2 using int variables and print the result. Then divide 9.0 by 2 and print that result. Compare the two outputs.

public class Demo5 {
    public static void main(String[] args) {
        int intResult = 9 / 2; 
        double doubleResult = 9.0 / 2; 
        
        System.out.println("Integer division result (9 / 2): " + intResult);
        System.out.println("Floating-point division result (9.0 / 2): " + doubleResult);
    }
}
