// Print the values of an int and a double side by side in one println statement using string concatenation (+).

public class Demo2 {
    public static void main(String[] args) {
        int myInt = 10;
        double myDouble = 20.5;
        
        System.out.println("The value of myInt is: " + myInt + "\nThe value of myDouble is: " + myDouble);
    }
    
}
